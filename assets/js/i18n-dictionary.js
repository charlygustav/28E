                ctxB.fillStyle = grad1;
                ctxB.beginPath();
                ctxB.moveTo(p.x, 0); ctxB.lineTo(p.x + pipeW, 0);
                ctxB.lineTo(p.x + pipeW, p.gapY - 15);
